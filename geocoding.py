# Départements de la grande couronne
DEPT_BOUNDS = {
    '77': {'lat': (48.2, 48.9), 'lon': (2.4, 3.5)},
    '78': {'lat': (48.5, 49.1), 'lon': (1.5, 2.2)},
    '91': {'lat': (48.2, 48.8), 'lon': (1.9, 2.6)},
    '95': {'lat': (48.9, 49.2), 'lon': (1.9, 2.7)},
}

ALL_COORDS = {**PARIS_COORDS, **IDF_KNOWN_COORDS}


def add_coordinates(df: pd.DataFrame, seed: int = 42) -> pd.DataFrame:
    np.random.seed(seed)
    df = df.copy()

    lats, lons = [], []

    for _, row in df.iterrows():
        cp   = str(row["Code postal"])[:5]
        dept = str(row["Code departement"])

        if cp in ALL_COORDS:
            lat, lon = ALL_COORDS[cp]
        elif dept in DEPT_BOUNDS:
            b   = DEPT_BOUNDS[dept]
            lat = np.random.uniform(*b["lat"])
            lon = np.random.uniform(*b["lon"])
        else:
            lat, lon = 48.85, 2.35  # centre IDF par défaut

        lats.append(lat)
        lons.append(lon)

    df["lat"] = lats
    df["lon"] = lons

    return df
